// Bakes Anybody (variable: wdth 50–150, wght 100–900) into point-compatible
// outlines on an instance grid, so the film can interpolate width and weight
// continuously on canvas (canvas fontStretch only takes keywords).
import * as fontkit from 'fontkit';
import { writeFileSync } from 'node:fs';

const font = fontkit.openSync(new URL('./fonts/Anybody.ttf', import.meta.url).pathname);
const CHARS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789ı().,-—';
const WDTH = [50, 75, 100, 125, 150];
const WGHT = [200, 500, 700, 900];
const upm = font.unitsPerEm;

const glyphs = {};
for (const ch of CHARS) {
  const g = { ops: null, adv: [], pts: [] };
  for (const w of WDTH) {
    for (const h of WGHT) {
      const inst = font.getVariation({ wdth: w, wght: h });
      const glyph = inst.glyphForCodePoint(ch.codePointAt(0));
      const cmds = glyph.path.commands;
      const ops = cmds.map(c => c.command[0] === 'c' && c.command !== 'closePath' ? 'C' : c.command === 'closePath' ? 'Z' : c.command === 'moveTo' ? 'M' : c.command === 'lineTo' ? 'L' : c.command === 'quadraticCurveTo' ? 'Q' : 'C').join('');
      if (g.ops === null) g.ops = ops;
      else if (g.ops !== ops) throw new Error(`incompatible outline for ${ch} at ${w}/${h}`);
      // y flipped to canvas space, in em units * 1000, rounded
      const pts = [];
      for (const c of cmds) for (let i = 0; i < c.args.length; i += 2) pts.push(Math.round(c.args[i] / upm * 1000), Math.round(-c.args[i + 1] / upm * 1000));
      g.pts.push(pts);
      g.adv.push(Math.round(glyph.advanceWidth / upm * 1000));
    }
  }
  glyphs[ch] = g;
}

const xh = font.getVariation({ wdth: 100, wght: 900 }).glyphForCodePoint('x'.codePointAt(0)).bbox.maxY / upm;
const cap = font.getVariation({ wdth: 100, wght: 900 }).glyphForCodePoint('H'.codePointAt(0)).bbox.maxY / upm;
const out = { wdth: WDTH, wght: WGHT, xHeight: +xh.toFixed(4), capHeight: +cap.toFixed(4), glyphs };
writeFileSync(new URL('./src/glyphs.js', import.meta.url), '// generated by bake-glyphs.mjs\nexport default ' + JSON.stringify(out) + ';\n');
console.log('baked', Object.keys(glyphs).length, 'glyphs ×', WDTH.length * WGHT.length, 'instances; xHeight', out.xHeight, 'cap', out.capHeight);
